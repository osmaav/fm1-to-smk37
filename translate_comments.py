def apply_phrases(text: str) -> str:
    """Замена устойчивых английских фраз на русские эквиваленты."""
    for en, ru in PHRASE_FIXES:
        text = re.sub(r'\b%s\b' % re.escape(en), ru, text, flags=re.IGNORECASE)
    return text


def find_comment_start(line: str):
    """Возвращает индекс первого # вне строковых литералов или None."""
    in_str = None
    j = 0
    while j < len(line):
        ch = line[j]
        if in_str:
            if ch == "\\":
                j += 2
                continue
            if line.startswith(in_str, j):
                j += len(in_str)
                in_str = None
                continue
        else:
            if ch in "\"'":
                in_str = ch * 3 if line.startswith(ch * 3, j) else ch
                j += len(in_str)
                continue
            if ch == "#":
                return j
        j += 1
    return None


def translate_inline(code_part: str, comment_part: str):
    """Перевод inline-комментария; возвращает новую строку или None."""
    text = comment_part.lstrip("#").strip()
    if not text or text.startswith("!"):
        return None
    new_text = translate_comment_text(text)
    if new_text is None or new_text == text:
        return None
    return code_part.rstrip() + "  # " + new_text


def translate_line(line: str) -> str:
    """Перевод одной строки комментария/docstring (текст после #)."""
    raw = line.strip()
    if not raw:
        return line
    low = raw.lower()
    for pat, repl in RULES:
        m = re.match(pat, low, flags=re.IGNORECASE)
        if m and "{0}" in repl:
            marker = repl.replace("{0}", "").strip().rstrip(":")
            tail = raw[len(m.group(0)) - len(m.group(1)):].strip().lstrip(":. ").strip()
            translated_tail = translate_words(apply_phrases(tail)) if tail else ""
            result = f"{marker}: {polish(translated_tail)}" if translated_tail else marker
            return result
    return polish(translate_words(apply_phrases(raw)))



def translate_words(text: str) -> str:
    """Перевод текста пословно по словарю WORD_MAP."""
    if not text:
        return ""
    # Сначала фразовые замены
    for phrase, ru in PHRASE_MAP.items():
        if re.search(r"\b" + re.escape(phrase) + r"\b", text, flags=re.IGNORECASE):
            text = re.sub(r"\b" + re.escape(phrase) + r"\b", ru, text, flags=re.IGNORECASE)
    tokens = re.split(r"(\W+)", text)
    out = []
    for tok in tokens:
        if not tok or re.match(r"^\W+$", tok):
            out.append(tok)
            continue
        key = tok.lower()
        if key in WORD_MAP:
            tr = WORD_MAP[key]
            if tok[0].isupper() and tr:
                tr = tr[0].upper() + tr[1:]
            out.append(tr)
        else:
            out.append(tok)
    result = "".join(out)
    # Схлопываем двойные пробелы, оставшиеся от удалённых артиклей
    result = re.sub(r"\s{2,}", " ", result).strip()
    return result


